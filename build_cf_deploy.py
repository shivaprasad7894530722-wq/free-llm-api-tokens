#!/usr/bin/env python3
"""Build the Cloudflare MCP `execute` payload that deploys this site to
Cloudflare Pages (project: free-llm-api-tokens).

Why: the Cloudflare MCP connector cannot use the Pages asset-upload endpoint
(it returns 'Authorization failed'), so the site is shipped as a Pages
`_worker.js` that embeds the static files and serves them directly.

Usage:  python3 build_cf_deploy.py [out_path]   (default /workspace/cf_deploy_payload.js)
Then call the Cloudflare MCP tool `execute` with code = "$file:<out_path>".
"""
import base64, json, subprocess, sys, os
from pathlib import Path

here = Path(__file__).resolve().parent
out = sys.argv[1] if len(sys.argv) > 1 else "/workspace/cf_deploy_payload.js"

CT = {
    ".html": "text/html; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".js": "text/javascript; charset=utf-8",
    ".json": "application/json; charset=utf-8",
    ".xml": "application/xml; charset=utf-8",
    ".txt": "text/plain; charset=utf-8",
    ".md": "text/plain; charset=utf-8",
    ".png": "image/png",
}
BINARY_SUFFIXES = {".png"}

SKIP_DIRS = {".git", "content", "templates", "__pycache__"}
SKIP_FILES = {"build_site.py", "build_cf_deploy.py", "update.py", "deploy.sh", "README.md", "_headers"}


def should_skip(rel: Path) -> bool:
    if any(part in SKIP_DIRS or (part.startswith(".") and part != ".nojekyll") for part in rel.parts):
        return True
    if rel.name in SKIP_FILES:
        return True
    if rel.suffix not in CT:
        return True
    return False


def routes_for(rel: Path):
    """Map a repo-relative file to the URL pathnames the worker should serve."""
    parts = rel.as_posix()
    if parts == "index.html":
        return ["/", "/index.html"]
    if parts == "404.html":
        return ["/404", "/404.html"]
    if rel.name == "index.html":
        folder = "/" + rel.parent.as_posix()
        return [folder, folder + "/", folder + "/index.html"]
    return ["/" + parts]


blobs = {}
for p in sorted(here.rglob("*")):
    if not p.is_file():
        continue
    rel = p.relative_to(here)
    if should_skip(rel):
        continue
    ct = CT[rel.suffix]
    if rel.suffix in BINARY_SUFFIXES:
        rec = {"body": base64.b64encode(p.read_bytes()).decode("ascii"), "ct": ct, "bin": True}
    else:
        rec = {"body": p.read_text(encoding="utf-8"), "ct": ct}
    for route in routes_for(rel):
        if route in blobs and blobs[route] != rec:
            raise SystemExit(f"route collision at {route} ({rel})")
        blobs[route] = rec

# Keep in sync with the `_headers` file generated by build_site.py.
# This worker is the live deploy path; Pages `_headers` is not applied to it.
# The previous wildcard Access-Control-Allow-Origin is omitted so other sites
# cannot fetch data.json from a browser without CORS.
SECURITY_HEADERS = {
    "strict-transport-security": "max-age=31536000; includeSubDomains",
    "x-content-type-options": "nosniff",
    "x-frame-options": "DENY",
    "referrer-policy": "strict-origin-when-cross-origin",
    "permissions-policy": "camera=(), microphone=(), geolocation=(), payment=(), usb=()",
    "content-security-policy": (
        "default-src 'self'; "
        "script-src 'self' 'unsafe-inline' https://www.googletagmanager.com https://www.google-analytics.com; "
        "style-src 'self' 'unsafe-inline' https://fonts.googleapis.com; "
        "font-src 'self' https://fonts.gstatic.com; "
        "img-src 'self' data: https://www.google-analytics.com https://www.googletagmanager.com https://*.google-analytics.com; "
        "connect-src 'self' https://www.google-analytics.com https://region1.google-analytics.com https://*.google-analytics.com https://*.analytics.google.com https://www.googletagmanager.com https://*.googletagmanager.com; "
        "frame-ancestors 'none'; "
        "base-uri 'self'; "
        "form-action 'self'; "
        "object-src 'none'; "
        "upgrade-insecure-requests"
    ),
}
DATA_USE_HEADER = (
    "Personal and research use only; no bulk commercial reuse without permission. "
    "See https://freellmapi.link/terms"
)

worker = """const FILES = %s;
const SECURITY = %s;
const DATA_USE = %s;
function bodyOf(f) {
  if (!f || !f.bin) return f && f.body;
  const bin = atob(f.body);
  const bytes = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) bytes[i] = bin.charCodeAt(i);
  return bytes;
}
function withSecurity(headers, pathname) {
  const out = Object.assign({}, SECURITY, headers);
  if (pathname === '/data.json') out['x-content-usage'] = DATA_USE;
  return out;
}
export default {
  async fetch(request) {
    const url = new URL(request.url);
    let p = url.pathname;
    if (p.length > 1 && p.endsWith('/')) p = p.slice(0, -1);
    let f = FILES[p] || FILES[p + '/'] || FILES[url.pathname];
    if (!f) {
      const nf = FILES['/404'] || FILES['/404.html'];
      return new Response(nf ? bodyOf(nf) : 'Not found', {
        status: 404,
        headers: withSecurity({ 'content-type': nf ? nf.ct : 'text/plain; charset=utf-8', 'cache-control': 'no-store' }, p)
      });
    }
    return new Response(bodyOf(f), { headers: withSecurity({ 'content-type': f.ct, 'cache-control': 'public, max-age=300' }, p) });
  }
};
""" % (json.dumps(blobs), json.dumps(SECURITY_HEADERS), json.dumps(DATA_USE_HEADER))

try:
    sha = subprocess.check_output(["git", "-C", str(here), "rev-parse", "HEAD"], text=True).strip()
    msg = subprocess.check_output(["git", "-C", str(here), "log", "-1", "--pretty=%s"], text=True).strip()
except Exception:
    sha, msg = "", "manual deploy"

code = """async () => {
  const P = 'free-llm-api-tokens';
  const worker = %s;
  const fields = { manifest: '{}', branch: 'main', commit_hash: %s, commit_message: %s, commit_dirty: 'false' };
  const b = '----cfpages' + Date.now();
  const parts = [];
  for (const [k, v] of Object.entries(fields)) parts.push('--' + b, `Content-Disposition: form-data; name="${k}"`, '', v);
  parts.push('--' + b, 'Content-Disposition: form-data; name="_worker.js"; filename="_worker.js"', 'Content-Type: application/javascript+module', '', worker, '--' + b + '--', '');
  const d = await cloudflare.request({ method: 'POST', path: `/accounts/${accountId}/pages/projects/${P}/deployments`, body: parts.join('\\r\\n'), contentType: 'multipart/form-data; boundary=' + b, rawBody: true });
  return { success: d.success, url: d.result && d.result.url, id: d.result && d.result.id, errors: d.errors };
}""" % (json.dumps(worker), json.dumps(sha), json.dumps(msg))
Path(out).write_text(code)
print(out, len(code), "bytes,", len(blobs), "routes,", len({id(b["body"]) for b in blobs.values()}), "unique bodies")
